let currentLang = localStorage.getItem('eh-lang') || 'en';

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('eh-lang', lang);
  applyTranslations();
}

function t(key) {
  return I18N[currentLang]?.[key] ?? I18N.en[key] ?? key;
}

function applyTranslations() {
  const dict = I18N[currentLang] || I18N.en;

  // Text content: data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] != null) el.textContent = dict[key];
  });

  // HTML content: data-i18n-html
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] != null) el.innerHTML = dict[key];
  });

  // Placeholders: data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key] != null) el.placeholder = dict[key];
  });

  // Lang toggle active state
  document.querySelectorAll('.lang-toggle button').forEach(btn => {
    const match = btn.getAttribute('onclick')?.match(/setLang\('(\w+)'\)/);
    if (match) btn.classList.toggle('active', match[1] === currentLang);
  });

  // Dispatch event for dynamic content
  document.documentElement.setAttribute('lang', currentLang);
  window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: currentLang } }));
}

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
});
